def main() -> int:
    target = os.environ.get("MOARCHY_SOLITAIRE_DIR")
    if not target:
        print(
            "set MOARCHY_SOLITAIRE_DIR first -- refusing to touch a real game",
            file=sys.stderr,
        )
        return 2
    stage = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("DEMO", "table")
    game = HOME if stage == "home" else TABLE
    out = Path(target)
    out.mkdir(parents=True, exist_ok=True)
    payload = {
        "schema": 1,
        "game": {
            "draw": 1,
            "finished": False,
            "recorded": False,
            "deck": game["deck"],
            "moves": game["moves"],
        },
        "stats": STATS,
    }
    (out / "solitaire.json").write_text(
        json.dumps(payload, indent=1) + "\n", encoding="utf-8"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
